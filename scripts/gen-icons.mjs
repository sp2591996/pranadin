#!/usr/bin/env node
/**
 * Generates src/components/icons.generated.ts from Phosphor Icons (MIT,
 * https://phosphoricons.com), keeping only the "regular" and "fill" weights
 * of the icons we use. Saves ~8 KB gzip versus the React package on the
 * first-load budget. Re-run after adding a name to ICONS:
 *   node scripts/gen-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Nav icons get both weights (filled when active); the rest only "regular" (D-033 look).
const NAV = ["SunHorizon", "Wind", "CalendarBlank", "NotePencil", "SpeakerHigh", "House", "Waveform", "CalendarHeart", "Notebook", "Bank", "PersonSimpleTaiChi", "Flame", "Sun"];
const PLAIN = ["UserCircle", "ArrowLeft", "Timer",  "ArrowRight", "Sparkle", "CheckCircle", "Quotes", "Globe", "MapPin", "FlowerLotus", "Clock", "SunDim", "X", "CaretDown"];
// Travel icons for the Yatra pages only (D-037): a separate file, so other pages do not carry them.
const TRAVEL = ["Airplane", "Train", "Car", "Bed", "ForkKnife", "Wallet", "FirstAid", "HandsPraying", "TShirt", "Path", "MapTrifold", "CalendarPlus", "Check"];
/** Trip planner only (kept apart so place pages do not load them). */
const PLANNER = ["Wallet", "Path", "MapTrifold", "CalendarPlus", "Check", "Info", "Plus", "Minus", "Trash", "Printer", "ShareNetwork", "Copy", "ArrowUp", "ArrowDown", "MagnifyingGlass", "Airplane", "Train", "Bus", "Car", "Bed", "ForkKnife", "House", "PiggyBank", "Lightning", "Scales", "HandsPraying", "Mountains"];
const ICONS = [...NAV, ...PLAIN];
const DEFS = join(process.cwd(), "node_modules", "@phosphor-icons", "react", "dist", "defs");

function build(names) {
  const out = {};
  for (const name of names) {
    const src = readFileSync(join(DEFS, `${name}.es.js`), "utf8");
    out[name] = {};
    for (const w of NAV.includes(name) ? ["regular", "fill"] : ["regular"]) {
      const start = src.indexOf(`"${w}",`);
      if (start < 0) throw new Error(`${name}: weight ${w} not found`);
      const end = src.indexOf("\n  ]", start);
      const block = src.slice(start, end);
      if (/createElement\("(?!path")/.test(block.replace(/createElement\(a\.Fragment/g, ""))) {
        throw new Error(`${name}/${w}: non-path element; extend the generator`);
      }
      out[name][w] = [...block.matchAll(/d: "([^"]+)"/g)].map((m) => m[1]);
    }
  }
  return out;
}

const header = `// GENERATED by scripts/gen-icons.mjs from Phosphor Icons (MIT). Do not edit.
`;
writeFileSync(
  join(process.cwd(), "src", "components", "icons.generated.ts"),
  `${header}export const ICON_PATHS = ${JSON.stringify(build(ICONS), null, 2)} as const;
export type IconName = keyof typeof ICON_PATHS;
`,
);
writeFileSync(
  join(process.cwd(), "src", "features", "yatra", "travel-icons.generated.ts"),
  `${header}export const TRAVEL_PATHS = ${JSON.stringify(build(TRAVEL), null, 2)} as const;
export type TravelIconName = keyof typeof TRAVEL_PATHS;
`,
);
writeFileSync(
  join(process.cwd(), "src", "features", "yatra", "planner-icons.generated.ts"),
  `${header}export const PLANNER_PATHS = ${JSON.stringify(build(PLANNER), null, 2)} as const;
export type PlannerIconName = keyof typeof PLANNER_PATHS;
`,
);
console.log(`[gen-icons] ${ICONS.length} icons + ${TRAVEL.length} travel + ${PLANNER.length} planner icons`);
